    await page.getByRole('region',{name:'Search results'}).getByRole('button').filter({hasText:'Barbados Blue Loan for Marine Conservation'}).click()
    await expect(arrangement).toContainText('Institutional investors')
    await expect(arrangement).toContainText('FirstCaribbean International Bank (Barbados) Limited')
    await expect(arrangement).toContainText('Not established in the reviewed sources')
    await page.getByLabel('Relationship type',{exact:true}).selectOption('risk')
    const chart=page.getByRole('region',{name:'Climate finance network'})
    await expect(chart.locator('.focused-network-heading p')).toHaveText('4 participants · 3 connections')
    await chart.getByText(/^Connections in this view/).click()
    await page.getByRole('list',{name:'Documented connections'}).getByRole('button').filter({hasText:'TNC → Barbados Blue Loan'}).click()
    const connection=page.getByRole('complementary',{name:'Connection summary'})
    await expect(connection).toContainText('USD 50,000,000')
    await expect(connection).toContainText('Guarantee coverage')
    await expect(connection).toContainText('not a capital transfer')
    await page.screenshot({path:`${screenshots}/08-guarantee-${size}.png`,fullPage:false})
    await connection.getByRole('link',{name:'See relationship details'}).click()
    await expect(page).toHaveURL(/#relationship\//)
