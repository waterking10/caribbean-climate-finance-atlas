test('explores a canvas node, inspects evidence and changes network settings', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Network explorer' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Caribbean Development Bank', exact: true })).toBeVisible()
  const profile = page.getByRole('complementary', { name: 'Entity profile' })
  await expect(profile.getByRole('link', { name: 'Official website' })).toHaveAttribute('href', 'https://www.caribank.org/')
  await profile.getByText('What does this institution actually do?').click()
  await expect(profile.getByText(/eligible institutions pay for development priorities/)).toBeVisible()

  await page.getByRole('button', { name: 'Full network' }).click()
  await page.getByRole('button', { name: 'Fit network' }).click()
  const graph = page.getByTestId('graph-surface')
  await expect(graph.locator('canvas').first()).toBeVisible()
  await profile.getByRole('button', { name: 'Relationships' }).click()
  await profile.getByRole('button', { name: 'EIB Lends to' }).click()
  await expect(page.getByRole('complementary', { name: 'Relationship details' }).getByText('EUR 100,000,000')).toBeVisible()
  await page.getByRole('button', { name: 'Entity profile' }).click()
  const initial = { x: 334, y: 165 }
  const dragged = { x: initial.x + 42, y: initial.y - 25 }
  await graph.click({ position: initial })
  await expect(profile.getByRole('heading', { name: 'Green Climate Fund', exact: true })).toBeVisible()

  const bounds = (await graph.boundingBox())!
  await page.mouse.move(bounds.x + initial.x, bounds.y + initial.y)
  await page.mouse.down()
  await page.mouse.move(bounds.x + dragged.x, bounds.y + dragged.y, { steps: 8 })
  await page.mouse.up()
  await page.getByRole('list', { name: 'Matching entities' }).getByRole('button', { name: 'IDB Development bank', exact: true }).click()
  await graph.click({ position: dragged })
  await expect(profile.getByRole('heading', { name: 'Green Climate Fund', exact: true })).toBeVisible()
  const panning = (await graph.boundingBox())!
  await page.mouse.move(panning.x + 55, panning.y + 70)
  await page.mouse.down()
  await page.mouse.move(panning.x + 79, panning.y + 88, { steps: 8 })
  await page.mouse.up()
  await page.getByRole('list', { name: 'Matching entities' }).getByRole('button', { name: 'IDB Development bank', exact: true }).click()
  await graph.click({ position: { x: dragged.x + 24, y: dragged.y + 18 } })
  await expect(profile.getByRole('heading', { name: 'Green Climate Fund', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Isolate', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Show all' })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('region', { name: 'Institutional network' }).getByText('8 entities · 8 relationships')).toBeVisible()
  await page.getByRole('button', { name: 'Show all' }).click()

  await page.getByRole('button', { name: 'View', exact: true }).click()
  await page.getByLabel('Show node labels').uncheck()
  await page.getByLabel('Edge weighting').selectOption('USD · Commitment')
  await expect(page.getByText(/Thicker edges indicate larger disclosed amounts within USD/)).toBeVisible()
  await page.getByLabel('Edge weighting').selectOption('')
  await page.getByRole('button', { name: 'View', exact: true }).click()
  await page.getByRole('button', { name: 'Financing', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Financing', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('button', { name: 'Zoom in' }).click()
  await page.getByRole('button', { name: 'Zoom out' }).click()
  await profile.getByRole('button', { name: 'Relationships' }).click()
  await profile.getByRole('button', { name: 'CDB Accredited by' }).click()
  const relationship = page.getByRole('complementary', { name: 'Relationship details' })
  await expect(relationship.getByRole('heading', { name: 'Accredited by' })).toBeVisible()
  await expect(relationship.getByRole('link', { name: 'Caribbean Development Bank accredited entity profile' })).toHaveAttribute('href', /greenclimate\.fund/)
  expect(errors).toEqual([])
})

test('searches, filters and compares two or three entities', async ({ page }) => {
  await page.goto('/')
  const search = page.getByRole('searchbox', { name: 'Search institutions and funds' })
  await search.fill('FirstCaribbean')
  await expect(page.getByRole('heading', { name: 'CIBC Caribbean Bank Limited' })).toBeVisible()
  await page.getByLabel('Ownership', { exact: false }).selectOption('Public')
  await expect(page.getByText('No matching entities')).toBeVisible()
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await search.fill('Caribbean Development Bank')
  await page.getByRole('complementary', { name: 'Entity profile' }).getByRole('button', { name: 'Compare', exact: true }).click()
  await page.getByRole('navigation').getByRole('link', { name: /Compare/ }).click()
  const chooser = page.getByLabel('Add entity to comparison')
  await chooser.selectOption('idb')
  await expect(page.getByRole('table')).toBeVisible()
  await chooser.selectOption('eib')
  const table = page.getByRole('table')
  await expect(table.getByRole('button', { name: 'Caribbean Development Bank' })).toBeVisible()
  await expect(table.getByRole('button', { name: 'European Investment Bank' })).toBeVisible()
  await expect(table.getByRole('row').filter({ hasText: 'Ownership' }).locator('li.shared')).toHaveCount(3)
  const geography = table.getByRole('row', { name: /Geographic coverage/ })
  await geography.getByText('Show 15 more', { exact: true }).click()
  await expect(geography.getByText('Turks and Caicos Islands')).toBeVisible()
  await page.getByRole('button', { name: 'Remove EIB' }).click()
  await expect(table.getByRole('button', { name: 'European Investment Bank' })).toHaveCount(0)
})

