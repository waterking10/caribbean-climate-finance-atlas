    await expect(page.getByText(/IDB controls programme-level loan disbursements/).first()).toBeVisible()
    await expect(page.getByRole('link',{name:/Loan Contract 4865\/OC-BA/}).first()).toHaveAttribute('href',/^https:/)
    await page.getByRole('button',{name:'Back to network',exact:true}).click()
