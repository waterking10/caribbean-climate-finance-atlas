    await expect(page.getByLabel('Relationship type',{exact:true})).toHaveValue('risk')
    await expect(connection).toContainText('Guarantee coverage')
    await page.getByLabel('Geography',{exact:true}).selectOption('jamaica')
    await expect(chart.getByText('No matching connections',{exact:true})).toBeVisible()
    await search.fill('CDB')
    await expect(page.getByRole('region',{name:'Search results'})).toContainText('Caribbean Development Bank')
