import { expect, test } from '@playwright/test'

test('shows exactly three primary filters and keeps only supported advanced dimensions',async({page})=>{
  await page.goto('/#network')
  await expect(page.getByRole('complementary',{name:'Network filters'}).locator('select:visible')).toHaveCount(3)
  await expect(page.getByLabel('Relationship type',{exact:true})).toBeVisible()
  await expect(page.getByLabel('Geography',{exact:true})).toBeVisible()
  await expect(page.getByLabel('Financing theme',{exact:true})).toBeVisible()
  await expect(page.getByLabel('Financing sector',{exact:true})).toHaveCount(0)
  await page.getByText('Advanced filters',{exact:true}).click()
  const types=page.getByLabel('Institution type',{exact:true})
  await expect(types.locator('option')).toHaveCount(11)
  await types.selectOption('development_finance')
  await expect(page.getByRole('button',{name:'Reset filters',exact:true})).toBeEnabled()
  await expect(page.getByRole('list',{name:'Visible institutions'}).getByRole('button',{name:'CDB Development bank',exact:true})).toBeVisible()
  await page.getByLabel('Ownership',{exact:true}).selectOption('Multilateral')
  await page.getByLabel('Financing instrument',{exact:true}).selectOption('loan')
  await expect(page.getByRole('region',{name:'Climate finance network'})).not.toContainText('No matching connections')
  await page.getByRole('button',{name:'Reset filters',exact:true}).click()
  await expect(types).toHaveValue('')
  await expect(page.getByLabel('Ownership',{exact:true})).toHaveValue('')
  await expect(page.getByLabel('Financing instrument',{exact:true})).toHaveValue('')
})

test('keeps mobile filtering compact and searchable outside the initial selection',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('/#network')
  await expect(page.getByRole('complementary',{name:'Network filters'}).locator('select:visible')).toHaveCount(3)
  await page.getByText('Advanced filters',{exact:true}).click()
  await expect(page.getByLabel('Institution type',{exact:true})).toBeVisible()
  await page.getByLabel('Relationship type',{exact:true}).selectOption('risk')
  await page.getByLabel('Geography',{exact:true}).selectOption('jamaica')
  await page.getByRole('searchbox').fill('Energy Smart')
  await expect(page.getByRole('region',{name:'Search results'})).toContainText('Barbados Energy Smart Fund II')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})
